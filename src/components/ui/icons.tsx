type Drawing = readonly string[];

const flipX = (rows: Drawing) => rows.map((r) => [...r].reverse().join(""));
const flipY = (rows: Drawing) => [...rows].reverse();
const turn = (rows: Drawing) => rows.map((_, x) => rows.map((r) => r[x]).reverse().join(""));

const drawings: Record<string, Drawing> = {
  ...art,
  "arrow-left": flipX(art["arrow-right"]),
  "arrow-down": turn(art["arrow-right"]),
  "arrow-up": flipY(turn(art["arrow-right"])),
  "chevron-up": flipY(art["chevron-down"]),
  "chevron-right": turn(flipY(art["chevron-down"])),
  "chevron-left": flipX(turn(flipY(art["chevron-down"]))),
  upload: flipY(art.download),
};

function toPath(rows: Drawing) {
  let d = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let w = 1;
      while (row[x + w] === "#") w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w;
    }
  });
  return d;
}

