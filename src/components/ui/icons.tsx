type Drawing = readonly string[];

const flipX = (rows: Drawing) => rows.map((r) => [...r].reverse().join(""));
const flipY = (rows: Drawing) => [...rows].reverse();
const turn = (rows: Drawing) => rows.map((_, x) => rows.map((r) => r[x]).reverse().join(""));

const drawings: Record<string, Drawing> = {
  ...art,
  "arrow-left": flipX(art["arrow-right"]),
  "arrow-down": turn(art["arrow-right"]),
  "arrow-up": flipY(turn(art["arrow-right"])),
  "chevron-up": flipY(art["chevron-down"]),
  "chevron-right": turn(flipY(art["chevron-down"])),
  "chevron-left": flipX(turn(flipY(art["chevron-down"]))),
  upload: flipY(art.download),
};

function toPath(rows: Drawing) {
  let d = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let w = 1;
      while (row[x + w] === "#") w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w;
    }
  });
  return d;
}

const paths = Object.fromEntries(Object.entries(drawings).map(([k, v]) => [k, toPath(v)]));

export type IconName = keyof typeof art | "arrow-left" | "arrow-down" | "arrow-up" | "chevron-up" | "chevron-right" | "chevron-left" | "upload";
export const iconNames = Object.keys(drawings).sort() as IconName[];

const scales = { sm: 1.5, md: 2, lg: 3, xl: 5 };

export function Icon({
  name,
  size = "md",
  label,
  className,
}: {
  name: IconName;
  size?: keyof typeof scales;
  label?: string;
  className?: string;
}) {
  const px = 9 * scales[size];
  return (
    <svg
      viewBox="0 0 9 9"
      width={px}
      height={px}
      shapeRendering="crispEdges"
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      className={cn("pixel shrink-0 fill-current", className)}
      style={pixelBox(9, 9, scales[size])}
    >
      <path d={paths[name]} />
    </svg>
  );
}
